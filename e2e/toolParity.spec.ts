/**
 * Tool parity, browser half: runs tests/fixtures/tool_script.json through the
 * TS executor in the real app (window.scrub.tool) and records every result.
 *
 * TOOL_PARITY_WRITE=1 (`make tool-parity`) writes them to
 * tests/fixtures/tool_parity_ts.json, which backend/tests/test_tool_parity.py
 * then compares with the Python executor. Otherwise the run must reproduce the
 * committed fixture exactly, so a TS change that alters a result fails here.
 */

import { readFileSync, writeFileSync } from 'node:fs';

import { expect, test } from './fixtures.ts';

interface Section {
  case: string;
  calls: { tool: string; args: Record<string, unknown> }[];
}

const SCRIPT = new URL('../tests/fixtures/tool_script.json', import.meta.url);
const OUT = new URL('../tests/fixtures/tool_parity_ts.json', import.meta.url);

test('the tool script through the TS executor', async ({ page }) => {
  test.setTimeout(600_000);
  const script = JSON.parse(readFileSync(SCRIPT, 'utf8')) as { sections: Section[] };
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.goto('/?hands=off&voice=off&tutorial=0');
  await page.waitForFunction(() => window.scrub?.state.phase === 'ready');
  await page.evaluate(() => (window.scrub!.renderer.stepsOverride = 16));

  const sections: { case: string; results: Record<string, unknown>[] }[] = [];
  for (const section of script.sections) {
    await page.evaluate((id) => window.scrub!.freshCase(id), section.case);
    const results: Record<string, unknown>[] = [];
    for (const call of section.calls) {
      const r = await page.evaluate(([n, a]) => window.scrub!.tool(n, a), [call.tool, call.args] as const);
      results.push(r);
    }
    sections.push({ case: section.case, results });
  }

  const out = { about: 'Generated by e2e/toolParity.spec.ts from tool_script.json; do not edit.', sections };
  if (process.env.TOOL_PARITY_WRITE === '1') {
    writeFileSync(OUT, `${JSON.stringify(out, null, 2)}\n`);
  } else {
    const want = JSON.parse(readFileSync(OUT, 'utf8')) as typeof out;
    expect(sections).toEqual(want.sections);
  }
});
